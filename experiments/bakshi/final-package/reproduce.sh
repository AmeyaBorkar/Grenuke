#!/usr/bin/env bash
# Reproduce the submitted model, from the raw challenge TSVs to output/*.tsv.
#
# In the submission zip this is code/business_entity_resolution/src/reproduce.sh and the model scripts are
# code/business_entity_resolution/src/model_v1/, so run it as:
#
#     MODEL_DIR="$PWD/code/business_entity_resolution/src/model_v1" \
#       bash code/business_entity_resolution/src/reproduce.sh
#
# THE SUBMITTED MODEL IS Composite B, the default: VARIANT=compositeB (public 0.990879; driver src/box/compositeB.sh).
# The single-chain variants below remain available and are what Composite B builds on.
# The whole self-training family reduces to two choices -- which cross-encoder mix stage 2 sees, and which
# teacher supplies the French pseudo-labels -- so one script covers all of them and the differences stay
# visible instead of being buried in separate copies.
#
#   VARIANT   stage-2 cross-encoder group            French pseudo-labels (teacher)
#   -------   ------------------------------------   ------------------------------
#   v7n       cem2 = e5l + e5l2                      none
#   v7nst     cem2 = e5l + e5l2                      v7ce3            <- 0.990179, the measured best
#   v7nst2    cem2 = e5l + e5l2                      v7nst (round 2)
#   v7mst     cem  = e5l + e5l2 + bge                v7ce3
#   v7s       cms  = e5l + e5ls + bge                v7ce3
#   v7sq      cmq  = e5l + qst + e5ls + bge          v7ce3
#   compositeB  US/India of g1w (cmq + Qwen2.5-7B x2) + France of mixmdp - 7B rejects   <- 0.990879, the submitted best
#   v7ens2    average of v7nst and v7nst2 stage-2 scores (bag_scores.py)
#   v7ensall  average of v7nst, v7mst, v7s and v7sq stage-2 scores
#   v7sb      recognised but NOT implemented: its feature-group tag was never stated (see the case below)
#   v7ensall2 recognised but NOT implemented: its seven bagged stage-2 tags were never listed
#
# STACK=1 (the default) also runs the stacked-rules pass after the acronym join, producing the "-dpc" tag
# that every 27 Sep final candidate uses. STACK=0 stops at the pre-stack model.
#
# WHY THE TEACHER MATTERS. Every self-trained variant needs a FINISHED earlier chain to label France with,
# and that chain must be built first. Round 1 is taught by v7ce3, which needs e5-base -- a model that appears
# nowhere in the student's own feature set. Cached pseudo-labels are not an acceptable undeclared input, so
# this script builds the teacher.
#
# HARDWARE. Reference: integration machine, RTX 5070 Ti 12 GB, 24 cores, 31 GB RAM, plus a rented H100 80 GB
# for ce_box.py / ce_llm_st.py.
#   - Stages 1-3 peak at 18-19 GB RAM each. Run nothing else heavy beside them, and note that a full run
#     contains several stage-2 fits (the teacher, the student, and one per bagged member): they must run
#     SERIALLY, not side by side.
#   - e5-large at --batch 128 --max-len 96 does not fit in 12 GB; the submitted runs used the H100. On a
#     smaller card lower --batch (32 works) and expect 4-6x the time.
#   - On torch 2.11 the non-finite-step guard in ce.train_one is MANDATORY. Without it a single bad gradient
#     step turns every weight into NaN. torch 2.14 never hit that path. See requirements.txt.
#
# DETERMINISM. XGBoost with fixed seeds is reproducible on the same machine. The cross-encoders are NOT
# bit-reproducible across GPUs, so a rerun can move a handful of pairs and change the output sha256. The
# reference check is then the holdout macro F0.5 in work/reports/<model tag>.json, not the file hash. The
# bytes that were uploaded are shipped verbatim in output/ and are never regenerated by this script.
set -euo pipefail

VARIANT="${VARIANT:-compositeB}"

# Composite B, the team's best submission (public 0.990879), chains finished models: the v7sq chain below, the
# Qwen2.5-7B cross-encoder q7st, the g1w stage 2, the 7B re-check and the France block. Its driver lives with the 7B
# code (src/box/compositeB.sh in the package, experiments/bakshi/box/ in the repository) and calls this script back
# with VARIANT=v7sq for the shared chain.
if [ "$VARIANT" = compositeB ]; then
  HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  if [ -f "$HERE/box/compositeB.sh" ]; then exec bash "$HERE/box/compositeB.sh"; fi          # package: src/reproduce.sh
  if [ -f "$HERE/src/box/compositeB.sh" ]; then exec bash "$HERE/src/box/compositeB.sh"; fi
  exec bash "$HERE/../box/compositeB.sh"
fi

ROOT="$(pwd)"
export BER_DATA_DIR="${BER_DATA_DIR:-$ROOT/student_resource/dataset}"
export BER_WORK_DIR="${BER_WORK_DIR:-$ROOT/work}"
export BER_OUTPUT_DIR="${BER_OUTPUT_DIR:-$ROOT/output}"
M="${MODEL_DIR:-$ROOT/experiments/ameya/model-v1}"
# PYTHONPATH must contain BOTH the model dir and the package src: stack/*.py import `post_ops` and `common`
# from $M, and everything imports `ber` from src.
# Windows note: Python there splits PYTHONPATH on ';', not ':'. Under Git Bash this is handled for you --
# MSYS converts a ':'-separated list of POSIX paths (/c/...) to 'C:\...;C:\...' when it launches python.exe.
# That works because $ROOT comes from `pwd`, which is POSIX-style there. If you override MODEL_DIR, give it a
# POSIX-style path (/c/Users/...) rather than C:\Users\..., or the list will not be split correctly.
export PYTHONPATH="$M:$ROOT/code/business_entity_resolution/src:${PYTHONPATH:-}"
export CE_BOX_DIR="${CE_BOX_DIR:-$BER_WORK_DIR/box}"
mkdir -p "$CE_BOX_DIR"

LEG=leg__rel,leg__n_s1,leg__n_r,leg__inter,leg__s1_only,leg__r_only
NX=nx__d1,nx__nudge,nx__digit_sub,nx__digit_swap,nx__suffix,nx__len_diff

# ---- what this variant needs -------------------------------------------------------------------------
# CE_RUNS: the ce_box/ce_llm_st runs the mix averages.  GROUP/COL: the stage-2 feature group.
# TEACHER: which finished chain labels France, or "" for none.  BAG: stage-2 tags to average, or "".
case "$VARIANT" in
  v7n)      CE_RUNS="e5l e5l2";           GROUP=cem2; TEACHER="";       BAG="" ;;
  v7nst)    CE_RUNS="e5l e5l2";           GROUP=cem2; TEACHER=v7ce3;    BAG="" ;;
  v7nst2)   CE_RUNS="e5l e5l2";           GROUP=cem2; TEACHER=v7nst;    BAG="" ;;
  v7mst)    CE_RUNS="e5l e5l2 bge";       GROUP=cem;  TEACHER=v7ce3;    BAG="" ;;
  v7s)      CE_RUNS="e5l e5ls bge";       GROUP=cms;  TEACHER=v7ce3;    BAG="" ;;
  v7sq)     CE_RUNS="e5l qst e5ls bge";   GROUP=cmq;  TEACHER=v7ce3;    BAG="" ;;
  v7ens2)   CE_RUNS="";                   GROUP="";   TEACHER="";       BAG="ameya-s2-v7nst,ameya-s2-v7nst2" ;;
  v7ensall) CE_RUNS="";                   GROUP="";   TEACHER="";       BAG="ameya-s2-v7nst,ameya-s2-v7mst,ameya-s2-v7s,ameya-s2-v7sq" ;;
  # ---- round 2: taught by v7sq-dpc, the best MEASURED model (public 0.990545) rather than by v7ce3 ----
  # This is a TWO-ROUND teacher chain. v7sq must be built first, stack included, because its -dpc decisions
  # are what label France. The guard below refuses to run if it has not been.
  v7sqr2)   CE_RUNS="e5l qst e5ls bge";   GROUP=cmq;  TEACHER=v7sq;     BAG="" ;;
  v7sq5)    CE_RUNS="e5l qstr2 e5lsr2 bge"; GROUP=cmq5; TEACHER=v7sq;   BAG="" ;;
  # Deliberately NOT guessed. These two exist as packages but their tags were never written down, and a
  # wrong feature-group or bag name here would silently reproduce a different model than the one shipped.
  v7sb)  echo "VARIANT=v7sb needs its stage-2 feature-group tag confirmed (the mix is e5l + e5ls + bges, but the group name is not recorded). Confirm it, add a line here, and rerun." >&2; exit 4 ;;
  v7ensall2) echo "VARIANT=v7ensall2 needs its seven bagged stage-2 tags listed (it includes bges and the second e5ls seed). Confirm them, add the BAG line here, and rerun." >&2; exit 4 ;;
  *) echo "unknown VARIANT '$VARIANT'" >&2; exit 2 ;;
esac
COL="${GROUP:+${GROUP}__logit}"
echo "== reproducing VARIANT=$VARIANT  group=${GROUP:-(bagged)}  teacher=${TEACHER:-none}  bag=${BAG:-none} =="

echo "== 0. records and the Indic->Latin dictionary (learned on train folds 5-19 only) =="
python -m ber.pipeline --stage records --split train
python -m ber.pipeline --stage records --split test
python "$M/feats.py" --split train --tag ameya-fx1 --dict-only

echo "== 1. blocking v3 (~13 + 10 min) =="
BP="--set trim_s1=15 --set trim_r=4 --set indic_dict=ameya-fx1 --set ns_ngrams=4 --set ns_domain_len=8 --set nw_words=6"
python -m ber.pipeline --stage block --split train --tag ameya-block-v3 $BP
python -m ber.pipeline --stage block --split test  --tag ameya-block-v3 $BP

cd "$M"

echo "== 2. pair features, bundle ameya-fx5 (~1 h). Each train run writes a table its test run reads. =="
python feats.py --cands ameya-block-v3 --split train --tag ameya-fx5
python feats.py --cands ameya-block-v3 --split test  --tag ameya-fx5
python feats_nx.py     --feats ameya-fx5 --split train
python feats_nx.py     --feats ameya-fx5 --split test
python feats_lo.py     --feats ameya-fx5 --split train
python feats_lo.py     --feats ameya-fx5 --split test
python feats_legal.py  --feats ameya-fx5 --split train
python feats_legal.py  --feats ameya-fx5 --split test
python feats_lo_proxy.py --feats ameya-fx5 --split train --calib
python feats_lo_proxy.py --feats ameya-fx5 --split test
python lo_mix.py --feats ameya-fx5

echo "== 3. stage 0 + 1 on all of train, 4 out-of-fold groups (~30 min, ~18 GB) =="
python s1.py --feats ameya-fx5 --tag ameya-s1-v6all --groups str,cx,lo0,lg,nx \
  --drop leg__r_only_bits,leg__s1_only_bits --all

echo "== 4. e5-small cross-encoder feature, group 'ce' (MIT, 118M; GPU ~40 min) =="
python ce.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag ameya-ce-v6 --model intfloat/multilingual-e5-small

echo "== 5. export the uncertain band once, for every ce_box.py / ce_llm_st.py run =="
python -c "from ce import band_pairs; import os; d=os.environ['CE_BOX_DIR']; [band_pairs('ameya-s1-v6all', s)[['s1','r','row','p1'] + (['fold','y'] if s == 'train' else [])].to_parquet(f'{d}/band_{s}.parquet', index=False) for s in ('train','test')]"

echo "== 6. TEACHER v7ce3: built only to produce the French pseudo-labels =="
# e5-large 1 epoch (cel) and e5-base (ceb). e5-base is in the teacher's feature set and NOT the student's.
python ce_box.py --model intfloat/multilingual-e5-large --name e5l  --lr 2e-5 --batch 128 --epochs 1 --seed 26
python ce_box.py --model intfloat/multilingual-e5-base  --name e5b  --lr 3e-5 --batch 128 --epochs 1 --seed 26
python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_e5l" --group cel --column cel__logit
python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_e5b" --group ceb --column ceb__logit
python s2.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag ameya-s2-v7ce3 \
  --groups str,cx,lo0,lg,ce,cel,ceb,nx --cluster --extra "$LEG,ce__logit,cel__logit,ceb__logit,$NX" --all
python decide.py --scores ameya-s2-v7ce3 --col pc --tag ameya-model-v7ce3-c2 --p-cand 0.02 --top-r 2
# The c2 candidate set. Every later stage takes it as --cands, including the student's.
python cands_final.py --s1 ameya-s1-v6all --tag ameya-cands-v6all-c2 --p-cand 0.02 --top-r 2
python stage3.py --scores ameya-s2-v7ce3 --tag ameya-s3-v7ce3 --p-cand 0.02 --top-r 2
python decide.py --scores ameya-s3-v7ce3 --col pc --tag ameya-model-v7ce3-s3 --p-cand 0.02 --top-r 2
python post_ops.py --matches ameya-model-v7ce3-s3 --scores ameya-s3-v7ce3 --cands ameya-cands-v6all-c2 \
  --feats ameya-fx5 --tag ameya-model-v7ce3-s3-ops3 --robust-addr
python acr_join.py --split test --matches ameya-model-v7ce3-s3-ops3 --cands ameya-cands-v6all-c2 \
  --tag ameya-model-v7ce3-s3-ops3a --cands-tag ameya-cands-v7ce3-c2a

pseudo_for () {   # $1 = teacher tag, $2 = its FINAL matches tag -> writes both label files, echoes the stage-2 one
  local t="$1" fin="$2"
  python pseudo_labels.py "ameya-model-$t-s3" "ameya-s3-$t" "ameya-model-$t-s3-ops3" \
    "$fin" "s1:ameya-s1-v6all" "$CE_BOX_DIR/pseudo_s2_fr_$t.parquet" >&2
  python pseudo_labels.py "ameya-model-$t-s3" "ameya-s3-$t" "ameya-model-$t-s3-ops3" \
    "$fin" "$CE_BOX_DIR/band_test.parquet" "$CE_BOX_DIR/pseudo_fr_$t.parquet" >&2
  echo "$CE_BOX_DIR/pseudo_s2_fr_$t.parquet"
}

if [ -n "$TEACHER" ]; then
  echo "== 7. pseudo-labels for the unlabelled country, from $TEACHER's final decisions =="
  # y=1: in the final matches with pc >= 0.9, or added by the rules / the acronym join.
  # y=0: not in the final matches with pc <= 0.05, or an op-B prediction the rules dropped.  y=-1: unlabelled.
  #
  # Which of the teacher's tags counts as "final" depends on whether the teacher was stacked. v7ce3 predates
  # the stack, so its final is -s3-ops3a. Round-2 teachers are stacked, so theirs is -s3-ops3a-dpc, and using
  # the pre-stack tag would silently label France from a DIFFERENT set of decisions than the teacher's
  # measured output.
  if [ "$TEACHER" = "v7ce3" ]; then
    TFIN="ameya-model-$TEACHER-s3-ops3a"
  else
    TFIN="ameya-model-$TEACHER-s3-ops3a-dpc"
    echo "   round 2: teacher is $TEACHER (stacked), final tag $TFIN" >&2
    echo "   its own chain must have been built first: VARIANT=$TEACHER STACK=1 bash reproduce.sh" >&2
  fi
  for t in "matches/$TFIN" "matches/ameya-model-$TEACHER-s3" "matches/ameya-model-$TEACHER-s3-ops3" \
           "scores/ameya-s3-$TEACHER"; do
    [ -d "$BER_WORK_DIR/$t" ] || {
      echo "   FAIL: teacher artifact $BER_WORK_DIR/$t is missing." >&2
      echo "   Build the teacher first: VARIANT=$TEACHER STACK=1 bash reproduce.sh" >&2
      exit 3; }
  done
  PSEUDO="$(pseudo_for "$TEACHER" "$TFIN")"
fi

S2=ameya-s2-$VARIANT
if [ -n "$BAG" ]; then
  echo "== 8. bagged stage 2: averaging $BAG =="
  echo "   each member must already exist: run this script once per member first." >&2
  python bag_scores.py --scores "$BAG" --tag "$S2"
else
  echo "== 8. the larger cross-encoders for this variant, then its stage 2 =="
  for r in $CE_RUNS; do
    case "$r" in
      e5l)  : ;;                                          # already built for the teacher
      e5l2) python ce_box.py --model intfloat/multilingual-e5-large --name e5l2 --lr 2e-5 --batch 128 --epochs 2 --seed 7 ;;
      bge)  python ce_box.py --model BAAI/bge-reranker-v2-m3 --name bge --lr 2e-5 --batch 128 --epochs 1 --seed 26 ;;
      # e5ls/qst and their round-2 twins e5lsr2/qstr2 are self-trained on the TEACHER's French band
      # pseudo-labels, cross-fitted by S1 group. The only difference between a round-1 and a round-2 run is
      # WHICH teacher wrote pseudo_fr_*, which is why one recipe covers both.
      e5ls|e5lsr2)
            python ce_box.py --model intfloat/multilingual-e5-large --name "$r" --lr 2e-5 --batch 128 \
                 --epochs 2 --seed 7 --pseudo "$CE_BOX_DIR/pseudo_fr_$TEACHER.parquet" ;;
      qst|qstr2)
            python ce_llm_st.py --model Qwen/Qwen2.5-1.5B --name "$r" --lr 1e-4 --batch 64 \
                 --pseudo "$CE_BOX_DIR/pseudo_fr_$TEACHER.parquet" --us-in-frac 0.5 ;;
    esac
  done
  # One group for the whole mix: the mean of the z-scored logits, z from the train band (zmean_ce.py).
  # Averaging rather than giving stage 2 each logit separately is deliberate -- on France the encoders
  # disagree 4x as often as on US/India, and a model given them separately extrapolates on that
  # disagreement. RESEARCH_v6.md 6.6, 6.13.
  SRC=""; for r in $CE_RUNS; do SRC="$SRC $CE_BOX_DIR/out_$r"; done
  python zmean_ce.py "$CE_BOX_DIR/out_$GROUP" $SRC
  python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_$GROUP" --group "$GROUP" --column "$COL"
  # --pseudo adds France's own test rows with pseudo-labels, split into 4 groups by fold_of % 4, so no
  # French pair is scored by a model that saw its own label. Early stopping and isotonic calibration use
  # LABELLED (US/India) rows only.
  python s2.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag "$S2" \
    --groups "str,cx,lo0,lg,ce,$GROUP,nx" --cluster --extra "$LEG,ce__logit,$COL,$NX" --all \
    ${TEACHER:+--pseudo "$PSEUDO"}
fi

echo "== 9. decision, stage 3, France rules v3, acronym join =="
MT=ameya-model-$VARIANT
python decide.py  --scores "$S2" --col pc --tag "$MT-c2" --base ameya-model-v7ce3-c2 --p-cand 0.02 --top-r 2
python stage3.py  --scores "$S2" --tag "ameya-s3-$VARIANT" --p-cand 0.02 --top-r 2
python decide.py  --scores "ameya-s3-$VARIANT" --col pc --tag "$MT-s3" --base ameya-model-v7ce3-s3 --p-cand 0.02 --top-r 2
python post_ops.py --matches "$MT-s3" --scores "ameya-s3-$VARIANT" --cands ameya-cands-v6all-c2 \
  --feats ameya-fx5 --tag "$MT-s3-ops3" --robust-addr
# acr_join appends acronym copies at the S1's own address to BOTH the matches and the candidate set, for
# countries without training labels only. It is why the submitted candidate file is not ameya-cands-v6all-c2.
python acr_join.py --split test --matches "$MT-s3-ops3" --cands ameya-cands-v6all-c2 \
  --tag "$MT-s3-ops3a" --cands-tag "ameya-cands-$VARIANT-c2a"

# ---- 9b. the stacked rules (the "-dpc" pass) ----------------------------------------------------------
# STACK=1 (default) adds one pass after acr_join: stack/stack.sh. Every final candidate from 27 Sep is a
# -dpc package, so this is ON by default; STACK=0 reproduces the pre-stack model instead.
#
# It decides PER COUNTRY GROUP, which is the whole point of the name:
#   - countries WITH training labels: an expected-F0.5 decision per S1 (logit shift 0.2, phantom 0.01,
#     crowd shift -0.3) plus the acronym and generator-cap rules. Gated at +48.1e-6 [+7.1, +91.2] on the
#     shared holdout over v7s, and +23.7e-6 out of sample under repeated 2-fold CV, positive in 86% of
#     splits (tuning the flat threshold instead gives -18.8e-6).
#   - countries WITHOUT labels: a narrowed hunt (number-dropped acronym adds only, no cap drops, because
#     French pc cannot rank near-identical copies), then the address polish - add same-name copies at the
#     exact address (99.99% true in US/India), drop cross-commune pairs (French true copies change commune
#     in 3 of 546,465). That last rule also fixes the acronym join's cross-city leak from RESEARCH_v6 6.14.
# The labelled countries are read from the train records, never hard-coded.
#
# It reuses the SAME candidate set as step 9 - it only adds or reclassifies pairs already inside
# ameya-cands-$VARIANT-c2a - so there is no new candidate tag, and matches stay a subset of candidates.
if [ "${STACK:-1}" = 1 ]; then
  echo "== 9b. stacked rules: per-country-group decision, acronym hunt and caps, French address polish =="
  bash "$M/stack/stack.sh" "$VARIANT"
  FINAL_TAG="$MT-s3-ops3a-dpc"
else
  echo "== 9b. STACK=0: skipping the stacked-rules pass =="
  FINAL_TAG="$MT-s3-ops3a"
fi

cd "$ROOT"

echo "== 10. write the organiser TSVs and validate (tag $FINAL_TAG) =="
python -m ber.pipeline --stage write --split test --tag "$FINAL_TAG" \
  --in "candidates=ameya-cands-$VARIANT-c2a" --in "matches=$FINAL_TAG"
python student_resource/utils/validate_submission.py \
  --matching "$BER_OUTPUT_DIR/matching_results.tsv" \
  --candidate "$BER_OUTPUT_DIR/candidate_pairs.tsv" --test-dir "$BER_DATA_DIR/test"

echo "== 11. strict audit (the official validator only WARNS about the checks that matter most) =="
# validate_submission.py prints PASS even when candidate_pairs.tsv is missing, and even when matched pairs
# fall outside it. It also never checks owner uniqueness or country consistency. This does, and fails on them.
python "${AUDIT:-$M/audit_matching.py}" \
  --matching "$BER_OUTPUT_DIR/matching_results.tsv" \
  --candidate "$BER_OUTPUT_DIR/candidate_pairs.tsv" --test-dir "$BER_DATA_DIR/test"

echo "== 12. hashes =="
sha256sum "$BER_OUTPUT_DIR/matching_results.tsv" "$BER_OUTPUT_DIR/candidate_pairs.tsv" 2>/dev/null \
  || shasum -a 256 "$BER_OUTPUT_DIR/matching_results.tsv" "$BER_OUTPUT_DIR/candidate_pairs.tsv"
cat <<'EOF'

Reference for VARIANT=v7nst, package 2026-09-27-v7nst-s3-ops3a-c2, public macro F0.5 0.990179:
  matching_results.tsv  sha256 659f5169cabbb2a3de2cb8580b614bbff718ea62d5b1fb4497243b50fcc34533  (97,909,982 bytes)
  candidate_pairs.tsv   sha256 510a33ea18a7ab4cd2ec5ad4e8ad113bbc4fd4f46818941c00f29852f3e258aa  (6,410,247 pairs)

Independently verified properties of that matching file: 1,732,544 rows (one per test S1), 5,856,096 pairs,
100,137 empty, 3.3801 per S1, 0 records claimed by more than one S1, 0 cross-country pairs, every target
present in test_source2/3.tsv, and 0 matched pairs outside the candidate file.
Holdout macro F0.5 0.991194 (US 0.991005, India 0.991472).

If the cross-encoders were rerun on different hardware the hashes will differ; compare
work/reports/ameya-model-<variant>-s3.json instead.
EOF
