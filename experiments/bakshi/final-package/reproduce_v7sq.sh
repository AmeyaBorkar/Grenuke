#!/usr/bin/env bash
# Reproduce the submitted model v7sq (package 2026-09-27-v7sq-s3-ops3a-dpc-c2, expected public macro F0.5 ~0.990295).
#
# In the submission zip this file is code/business_entity_resolution/reproduce.sh and the model scripts are
# code/business_entity_resolution/src/model_v1/, so run it as:
#
#     MODEL_DIR="$PWD/code/business_entity_resolution/src/model_v1" \
#       bash code/business_entity_resolution/reproduce.sh
#
# From a developer checkout instead, MODEL_DIR defaults to experiments/ameya/model-v1.
#
# WHAT THIS BUILDS, AND HOW IT DIFFERS FROM reproduce_v7nst.sh
# --------------------------------------------------------------
# v7sq is v7nst's design (a SELF-TRAINED student stage 2, teacher = v7ce3, pseudo-labels from the teacher's final
# decisions) with two changes:
#   1. The student's cross-encoder feature is the z-mean of FOUR runs instead of two: e5-large (seed 26),
#      e5-large self-trained on France (seed 7, --pseudo), bge-reranker-v2-m3, and Sachi's Qwen2.5-1.5B LoRA
#      cross-encoder self-trained on France (ce_llm_st.py, --pseudo). Group cmq replaces cem2.
#   2. After the student's rules + acronym join, an additional rule-stacking pass (stack.sh) runs on top: acronym
#      hunting/capping, a French-address "copy" and "city" polish, and an expected-F0.5 combo rule for labelled
#      countries, merged into one -dpc (decide-per-country) tag. This is the actual submitted matches tag.
#
#   shared stages 0-3  ->  4 cross-encoders (e5l, e5ls, bge, qst)  ->  z-mean group cmq
#                      ->  TEACHER v7ce3 (full chain to final matches, still e5-small + cel + ceb)
#                      ->  pseudo-labels from the teacher  ->  STUDENT v7sq (cmq + self-training)
#                      ->  rules v3 + acronym join  ->  stack.sh v7sq (the -dpc pass)  ->  write
#
# NOTE ON NAMING: v7nst's script names its second e5-large run "e5l2"; this script (and Ameya's PR comment) call
# the self-trained one "e5ls" to make the --pseudo distinction explicit. If the real ce_box.py output directory on
# disk is out_e5l2 rather than out_e5ls, adjust the zmean_ce.py call in step 5h to match.
#
# HARDWARE. Reference: the integration machine, RTX 5070 Ti 12 GB, 24 cores, 31 GB RAM, plus a rented H100 80 GB
# for the cross-encoders (4 runs here instead of v7nst's 3; e5ls and qst both use --pseudo and run longer).
#   - Stages 1 and 2 peak at about 18-19 GB RAM each. Run nothing else heavy beside them. There are TWO stage-2
#     fits here (v7ce3 the teacher, v7sq the student, each on all of train), so they must run SERIALLY.
#   - ce.py and ce_box.py/ce_llm_st.py need a CUDA GPU. e5-large at --batch 128 --max-len 96 does not fit in 12 GB;
#     the submitted runs used a rented H100 80 GB. On a smaller card lower --batch and expect several times the
#     time. ce_llm_st.py (Qwen2.5-1.5B, LoRA) fits on a single 24 GB card at --batch 32 with --grad-ckpt.
#   - Total on the reference machine plus one H100 for the encoders: roughly 8-10 h wall clock (longer than v7nst
#     because of the extra two cross-encoders and the stacking pass).
#
# DETERMINISM. XGBoost with fixed seeds is reproducible on the same machine. The cross-encoders are not
# bit-reproducible across GPUs (cuDNN kernel selection, TF32, non-deterministic reductions), so a rerun can move a
# handful of pairs and change the output sha256. The reference check is then the holdout macro F0.5 written to
# work/reports/<model tag>.json, not the file hash. The bytes that were uploaded are the bytes in output/ of the
# submitted package; they are shipped verbatim in the zip and are never regenerated by this script.
set -euo pipefail

ROOT="$(pwd)"
export BER_DATA_DIR="${BER_DATA_DIR:-$ROOT/student_resource/dataset}"
export BER_WORK_DIR="${BER_WORK_DIR:-$ROOT/work}"
export BER_OUTPUT_DIR="${BER_OUTPUT_DIR:-$ROOT/output}"
M="${MODEL_DIR:-$ROOT/experiments/ameya/model-v1}"
export PYTHONPATH="$M:$ROOT/code/business_entity_resolution/src:${PYTHONPATH:-}"
# Cross-encoder scratch dir: holds band_{train,test}.parquet and the out_<name>/ run dirs.
export CE_BOX_DIR="${CE_BOX_DIR:-$BER_WORK_DIR/box}"
mkdir -p "$CE_BOX_DIR"

LEG=leg__rel,leg__n_s1,leg__n_r,leg__inter,leg__s1_only,leg__r_only
NX=nx__d1,nx__nudge,nx__digit_sub,nx__digit_swap,nx__suffix,nx__len_diff

echo "== 0. records and the Indic->Latin dictionary (learned on train folds 5-19 only) =="
python -m ber.pipeline --stage records --split train
python -m ber.pipeline --stage records --split test
python "$M/feats.py" --split train --tag ameya-fx1 --dict-only

echo "== 1. blocking v3 (~13 + 10 min) =="
BP="--set trim_s1=15 --set trim_r=4 --set indic_dict=ameya-fx1 --set ns_ngrams=4 --set ns_domain_len=8 --set nw_words=6"
python -m ber.pipeline --stage block --split train --tag ameya-block-v3 $BP
python -m ber.pipeline --stage block --split test  --tag ameya-block-v3 $BP

cd "$M"

echo "== 2. pair features, bundle ameya-fx5 (~1 h). Each train run writes a table its test run reads: keep the order. =="
python feats.py --cands ameya-block-v3 --split train --tag ameya-fx5
python feats.py --cands ameya-block-v3 --split test  --tag ameya-fx5
python feats_nx.py --feats ameya-fx5 --split train
python feats_nx.py --feats ameya-fx5 --split test
python feats_lo.py --feats ameya-fx5 --split train
python feats_lo.py --feats ameya-fx5 --split test
python feats_legal.py --feats ameya-fx5 --split train
python feats_legal.py --feats ameya-fx5 --split test
python feats_lo_proxy.py --feats ameya-fx5 --split train --calib
python feats_lo_proxy.py --feats ameya-fx5 --split test
python lo_mix.py --feats ameya-fx5

echo "== 3. stage 0 + 1 on all of train, 4 out-of-fold groups (~30 min, ~18 GB) =="
python s1.py --feats ameya-fx5 --tag ameya-s1-v6all --groups str,cx,lo0,lg,nx \
  --drop leg__r_only_bits,leg__s1_only_bits --all

echo "== 4. cross-encoder feature, multilingual-e5-small (MIT, 118M; GPU ~40 min) =="
# The first run downloads the weights; afterwards HF_HUB_OFFLINE=1 works. Only used by the TEACHER (v7ce3); the
# student (v7sq) does not take a bare e5-small feature.
python ce.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag ameya-ce-v6 --model intfloat/multilingual-e5-small

echo "== 5. the larger cross-encoders (same band, same OOF groups) =="
# 5a. export the uncertain band once, for every ce_box.py / ce_llm_st.py run.
python -c "from ce import band_pairs; import os; d=os.environ['CE_BOX_DIR']; [band_pairs('ameya-s1-v6all', s)[['s1','r','row','p1'] + (['fold','y'] if s == 'train' else [])].to_parquet(f'{d}/band_{s}.parquet', index=False) for s in ('train', 'test')]"
# 5b. e5-large, 1 epoch, seed 26 (ce_box.py defaults)      -> teacher's `cel`, and one input of the student's z-mean
python ce_box.py --model intfloat/multilingual-e5-large --lr 2e-5 --name e5l
# 5c. e5-base, 1 epoch, seed 26                            -> teacher's `ceb` only (not used by the student)
python ce_box.py --model intfloat/multilingual-e5-base  --lr 3e-5 --name e5b
# 5d. e5-large, 2 epochs, seed 7, SELF-TRAINED on France   -> student input `e5ls`
#     Needs the teacher's pseudo-labels (produced in step 7), so this run happens AFTER step 7, not here; see
#     "5d (continued)" below. It is listed here with the other cross-encoders for readability only.
# 5e. bge-reranker-v2-m3 (Apache-2.0, 568M)                -> student input `bge`
python ce_box.py --model BAAI/bge-reranker-v2-m3 --lr 2e-5 --name bge
# 5f. import the TEACHER's two extra cross-encoders (e5-small from step 4 is imported by ce.py itself).
python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_e5l" --group cel --column cel__logit
python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_e5b" --group ceb --column ceb__logit

echo "== 6. TEACHER v7ce3: needed only to produce the student's pseudo-labels =="
# Stage 2 with all three cross-encoder logits as separate features (~25 min, ~19 GB).
python s2.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag ameya-s2-v7ce3 \
  --groups str,cx,lo0,lg,ce,cel,ceb,nx --cluster --extra "$LEG,ce__logit,cel__logit,ceb__logit,$NX" --all
python decide.py --scores ameya-s2-v7ce3 --col pc --tag ameya-model-v7ce3-c2 --p-cand 0.02 --top-r 2
# The c2 candidate set. Every later stage takes it as --cands, including the student's.
python cands_final.py --s1 ameya-s1-v6all --tag ameya-cands-v6all-c2 --p-cand 0.02 --top-r 2
python stage3.py --scores ameya-s2-v7ce3 --tag ameya-s3-v7ce3 --p-cand 0.02 --top-r 2
python decide.py --scores ameya-s3-v7ce3 --col pc --tag ameya-model-v7ce3-s3 --p-cand 0.02 --top-r 2
python post_ops.py --matches ameya-model-v7ce3-s3 --scores ameya-s3-v7ce3 --cands ameya-cands-v6all-c2 \
  --feats ameya-fx5 --tag ameya-model-v7ce3-s3-ops3 --robust-addr
python acr_join.py --split test --matches ameya-model-v7ce3-s3-ops3 --cands ameya-cands-v6all-c2 \
  --tag ameya-model-v7ce3-s3-ops3a --cands-tag ameya-cands-v7ce3-c2a

echo "== 7. pseudo-labels for the unlabelled country, from the teacher's final decisions =="
# y=1: in the final matches with pc >= 0.9, or added by the rules / the acronym join.
# y=0: not in the final matches with pc <= 0.05, or an op-B prediction the rules dropped.  y=-1: unlabelled.
# The band is every French stage-2 row of the stage-1 tag (about 1.43M rows; about 1.34M get a label).
python pseudo_labels.py ameya-model-v7ce3-s3 ameya-s3-v7ce3 ameya-model-v7ce3-s3-ops3 \
  ameya-model-v7ce3-s3-ops3a s1:ameya-s1-v6all "$CE_BOX_DIR/pseudo_s2_fr_v7ce3.parquet"
# The two cross-encoder-level self-trained runs (e5ls, qst) need the SAME pseudo-labelling, but keyed to the
# CE_BOX_DIR band's own row numbers, not the stage-2 (s1, r) table above.
python -c "
import pandas as pd
from ce import band_pairs
band = band_pairs('ameya-s1-v6all', 'test')[['s1', 'r', 'row']]
lab = pd.read_parquet('$CE_BOX_DIR/pseudo_s2_fr_v7ce3.parquet')
band.merge(lab, on=['s1', 'r'], how='inner').to_parquet('$CE_BOX_DIR/pseudo_fr_v7ce3.parquet', index=False)
"

echo "== 5d (continued). e5-large self-trained on France, seed 7, 2 epochs =="
python ce_box.py --model intfloat/multilingual-e5-large --lr 2e-5 --batch 128 --epochs 2 --seed 7 --name e5ls \
  --pseudo "$CE_BOX_DIR/pseudo_fr_v7ce3.parquet"

echo "== 5g. Sachi's Qwen2.5-1.5B LoRA cross-encoder (Apache-2.0, 1.5B), self-trained on France =="
# ce_llm_st.py imports experiments/sachi/ce_llm.py unchanged for the model/tokeniser/LoRA setup; it adds the
# pseudo-label sampling (--us-in-frac controls how much of the labelled US/India band each fold's model also sees)
# and a pair-separator token, since Qwen's tokeniser joins a text pair with no separator by default.
python ce_llm_st.py --model Qwen/Qwen2.5-1.5B --name qst \
  --pseudo "$CE_BOX_DIR/pseudo_fr_v7ce3.parquet" --us-in-frac 0.5

echo "== 5h. z-mean of the four student cross-encoders, then import as one stage-2 group (cmq) =="
python zmean_ce.py "$CE_BOX_DIR/out_cmq" "$CE_BOX_DIR/out_e5l" "$CE_BOX_DIR/out_qst" "$CE_BOX_DIR/out_e5ls" \
  "$CE_BOX_DIR/out_bge"
python ce_import.py --feats ameya-fx5 --src "$CE_BOX_DIR/out_cmq" --group cmq --column cmq__logit

echo "== 8. STUDENT v7sq: stage 2 with the cmq z-mean (e5l + qst + e5ls + bge), self-trained on France =="
# Same self-training mechanics as v7nst (French S1 split into groups; no French pair scored by a model that saw
# its own pseudo-label; early stopping and calibration use LABELLED rows only) but the cross-encoder group is cmq,
# not cem2, and cel/ceb are dropped (the teacher-only encoders play no part in the student).
python s2.py --feats ameya-fx5 --s1 ameya-s1-v6all --tag ameya-s2-v7sq \
  --groups str,cx,lo0,lg,ce,cmq,nx --cluster --extra "$LEG,ce__logit,cmq__logit,$NX" --all \
  --pseudo "$CE_BOX_DIR/pseudo_s2_fr_v7ce3.parquet"
python decide.py --scores ameya-s2-v7sq --col pc --tag ameya-model-v7sq-c2 \
  --base ameya-model-v7ce3-c2 --p-cand 0.02 --top-r 2
python stage3.py --scores ameya-s2-v7sq --tag ameya-s3-v7sq --p-cand 0.02 --top-r 2
python decide.py --scores ameya-s3-v7sq --col pc --tag ameya-model-v7sq-s3 \
  --base ameya-model-v7ce3-s3 --p-cand 0.02 --top-r 2

echo "== 9. France rules v3 (robust address matching), then the acronym join =="
python post_ops.py --matches ameya-model-v7sq-s3 --scores ameya-s3-v7sq --cands ameya-cands-v6all-c2 \
  --feats ameya-fx5 --tag ameya-model-v7sq-s3-ops3 --robust-addr
# acr_join appends acronym copies at the S1's own address to BOTH the matches and the candidate set, for countries
# without training labels only. It is why the candidate set below is not ameya-cands-v6all-c2.
python acr_join.py --split test --matches ameya-model-v7sq-s3-ops3 --cands ameya-cands-v6all-c2 \
  --tag ameya-model-v7sq-s3-ops3a --cands-tag ameya-cands-v7sq-c2a

echo "== 9b. rule stacking (stack.sh): acronym hunt/cap, French address copy/city polish, the labelled-country combo =="
# New step versus v7nst: applies extra label-free rules on top of the finished model, then an expected-F0.5 combo
# rule (with acronym+cap) on the countries that DO have training labels, and merges the two into one -dpc tag.
# See experiments/ameya/model-v1/stack/stack.sh's own header for what each of its five scripts does.
bash "$M/stack/stack.sh" v7sq
# stack.sh writes matches tag ameya-model-v7sq-s3-ops3a-dpc against the SAME candidates as step 9,
# ameya-cands-v7sq-c2a (stack.sh only adds/reclassifies pairs already in that candidate set; it does not need a
# new candidate file).

cd "$ROOT"

echo "== 10. write the organiser TSVs and validate =="
python -m ber.pipeline --stage write --split test --tag ameya-model-v7sq-s3-ops3a-dpc \
  --in candidates=ameya-cands-v7sq-c2a --in matches=ameya-model-v7sq-s3-ops3a-dpc
python student_resource/utils/validate_submission.py \
  --matching "$BER_OUTPUT_DIR/matching_results.tsv" \
  --candidate "$BER_OUTPUT_DIR/candidate_pairs.tsv" \
  --test-dir "$BER_DATA_DIR/test" --check-ids

echo "== 11. strict audit (the official validator only WARNS about the checks that matter most) =="
# validate_submission.py prints PASS even when candidate_pairs.tsv is missing, and even when matched pairs fall
# outside it. It also never checks owner uniqueness or country consistency. This does, and fails on them.
# audit_matching.py is shipped next to the model scripts (in a developer checkout it lives in
# experiments/bakshi/final-package/; AUDIT overrides the path if you run it from there).
python "${AUDIT:-$M/audit_matching.py}" \
  --matching "$BER_OUTPUT_DIR/matching_results.tsv" \
  --candidate "$BER_OUTPUT_DIR/candidate_pairs.tsv" \
  --test-dir "$BER_DATA_DIR/test"

echo "== 12. hashes =="
sha256sum "$BER_OUTPUT_DIR/matching_results.tsv" "$BER_OUTPUT_DIR/candidate_pairs.tsv" 2>/dev/null \
  || shasum -a 256 "$BER_OUTPUT_DIR/matching_results.tsv" "$BER_OUTPUT_DIR/candidate_pairs.tsv"
cat <<'EOF'

Submitted package 2026-09-27-v7sq-s3-ops3a-dpc-c2 (holdout macro F0.5 0.991246, US/India part 0.843258 vs v7nst's
0.843210; expected public macro F0.5 ~0.990295 -- TODO(bakshi/ameya): fill in the actual sha256, byte counts and
leaderboard score once this package is uploaded, matching the style of reproduce_v7nst.sh's own footer).

Models used, all MIT or Apache-2.0, all <= 8B parameters:
  intfloat/multilingual-e5-small (MIT, 118M) -- teacher only
  intfloat/multilingual-e5-base  (MIT, 278M) -- teacher only
  intfloat/multilingual-e5-large (MIT, 560M) -- e5l (teacher + student) and e5ls (student, self-trained)
  BAAI/bge-reranker-v2-m3 (Apache-2.0, 568M) -- student only
  Qwen/Qwen2.5-1.5B (Apache-2.0, 1.5B), LoRA fine-tuned -- student only, self-trained (qst)
  XGBoost (Apache-2.0) -- stages 0/1/2/3

If the cross-encoders were rerun on different hardware the hashes will differ; compare
work/reports/ameya-model-v7sq-s3.json (holdout macro F0.5 0.991246) instead. Note the -dpc stacking pass (step 9b)
changes some pairs after that report was written, so the file's own decide-stage number is the pre-stack figure;
the final submitted number is the leaderboard score above.
EOF
